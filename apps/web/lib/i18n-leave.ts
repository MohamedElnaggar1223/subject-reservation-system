const LATIN_RUN = /[A-Za-z](?:[A-Za-z0-9'’.&/+\-–]|\([^()\u0600-\u06FF]*\)| (?=[A-Za-z0-9(]))*/g;

/**
 * The Arabic sentence with every English run in it (a person's name, a
 * term's name, a reason the school typed) wrapped in Unicode isolates.
 */
export function translateLeaveText(text: string): string | null {
  const arabic = translateInner(text);
  return arabic === null ? null : arabic.replace(LATIN_RUN, (run) => `\u2068${run}\u2069`);
}

