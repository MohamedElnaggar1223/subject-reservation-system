const DAYS: Record<string, string> = {
  Sunday: 'الأحد', Monday: 'الاثنين', Tuesday: 'الثلاثاء', Wednesday: 'الأربعاء', Thursday: 'الخميس', Friday: 'الجمعة', Saturday: 'السبت',
};
const MONTHS: Record<string, string> = {
  January: 'يناير', February: 'فبراير', March: 'مارس', April: 'أبريل', May: 'مايو', June: 'يونيو',
  July: 'يوليو', August: 'أغسطس', September: 'سبتمبر', October: 'أكتوبر', November: 'نوفمبر', December: 'ديسمبر',
};
/** Weekdays and months in a date written by the API ("Sunday 4 October"). */
const day = (s: string) => s
  .replace(/\b(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday)\b/g, (d) => DAYS[d]!)
  .replace(/\b(January|February|March|April|May|June|July|August|September|October|November|December)\b/g, (m) => MONTHS[m]!);
/** "today", "tomorrow", "on Sunday 4 October". */
const when = (s: string) => (s === 'today' ? 'اليوم' : s === 'tomorrow' ? 'غدًا' : day(s.replace(/^on /, 'يوم ')));

